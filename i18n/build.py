# Builds the <script id="i18n"> block of sintrom-app.html from ui.py and legal_*.html.
import json, re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from ui import UI, VALENCIA
def valencia(t):
    for a, b in sorted(VALENCIA, key=lambda x: -len(x[0])):
        t = re.sub(r"(?<![\w·'’])" + re.escape(a) + r"(?![\w·])", b, t)
    return t
I18N = {'ca': {}, 'va': {}, 'gl': {}, 'eu': {}}
for es, ca, gl, eu in UI:
    I18N['ca'][es] = ca; I18N['va'][es] = valencia(ca); I18N['gl'][es] = gl; I18N['eu'][es] = eu
def legal(code):
    t = open(os.path.join(here, 'legal_' + code + '.html')).read()
    _, av, pr = re.split(r'<!--(?:aviso|privacidad)-->\n', t)
    return {'aviso': av, 'privacidad': pr}
LEGAL = {c: legal(c) for c in ('ca', 'gl', 'eu')}
LEGAL['va'] = {k: valencia(v) for k, v in LEGAL['ca'].items()}
block = ('<script id="i18n">\n// Translations, keyed by the Spanish text of the page. Generated by i18n/build.py; edit ui.py and legal_*.html there.\n'
         'const I18N = ' + json.dumps(I18N, ensure_ascii=False) + ';\nconst LEGAL = ' + json.dumps(LEGAL, ensure_ascii=False) + ';\n</script>\n')
p = sys.argv[1]; s = open(p).read()
if '<script id="i18n">' in s: s = re.sub(r'<script id="i18n">.*?</script>\n', lambda m: block, s, flags=re.S)
else: s = s.replace('<script>\n(function () {', block + '<script>\n(function () {', 1)
open(p, 'w').write(s)
keys = set(I18N['ca'])
miss = [k for k in re.findall(r"tr\('((?:[^'\\]|\\.)*)'", s) if k.replace("\\'", "'") not in keys]
print('missing tr keys:', miss)
